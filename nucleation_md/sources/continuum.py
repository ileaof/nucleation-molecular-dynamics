"""
Continuum source: builds States from the tables written by the continuum scripts
(Continuum_Mechanics_Solution/Scripts/), one entry per alloy in ALLOYS.

The scripts are NOT imported (importing runs the whole solution and rewrites the CSVs);
their tables and parameters are read as they are. Line numbers (Lxxx) refer to the
nucleation script of each alloy.

Row i of a table is one point of the continuum loop, r = req - i·dreq.
In `tablefull` (Al3Cu5Nb01Fe) the extra row with non-integer i (38.5) is the interpolated
experimental point (L1029-L1036).
"""
